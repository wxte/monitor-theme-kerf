"""Builds src/map-data.js, the dot-matrix world map: which cells of an
equirectangular grid are land, and where each country's marker goes.

  python3 tools/build_map.py <natural-earth-vector>/geojson

Reads ne_110m_land.geojson and ne_110m_admin_0_countries.geojson from Natural
Earth (public domain, naturalearthdata.com). A few places too small for the
1:110m set, but common homes for a server, are added by hand.
"""
import json, sys
from PIL import Image, ImageDraw

SRC = sys.argv[1]
COLS, LAT_TOP, LAT_BOTTOM = 84, 78.0, -56.0
STEP = 360 / COLS
ROWS = round((LAT_TOP - LAT_BOTTOM) / STEP)
SS = 8  # supersampling: a cell is land when enough of it is covered

img = Image.new("L", (COLS * SS, ROWS * SS), 0)
draw = ImageDraw.Draw(img)
xy = lambda lon, lat: ((lon + 180) / STEP * SS, (LAT_TOP - lat) / STEP * SS)

def polygons(geom):
    if geom["type"] == "Polygon": yield geom["coordinates"]
    elif geom["type"] == "MultiPolygon": yield from geom["coordinates"]

for f in json.load(open(f"{SRC}/ne_110m_land.geojson"))["features"]:
    for rings in polygons(f["geometry"]):
        draw.polygon([xy(*p[:2]) for p in rings[0]], fill=255)
        for hole in rings[1:]:
            draw.polygon([xy(*p[:2]) for p in hole], fill=0)

px = img.load()
bits = []
for r in range(ROWS):
    for c in range(COLS):
        cover = sum(px[c * SS + i, r * SS + j] > 0 for i in range(SS) for j in range(SS)) / (SS * SS)
        bits.append(cover >= 0.42)
# four cells to a hex digit, row by row
hexmask = "".join(f"{sum(b << (3 - i) for i, b in enumerate(bits[k:k + 4])):x}" for k in range(0, len(bits), 4))

places = {}
for f in json.load(open(f"{SRC}/ne_110m_admin_0_countries.geojson"))["features"]:
    p = f["properties"]
    code = p["ISO_A2_EH"]
    if len(code) == 2 and code.isalpha():
        places[code] = (p["LABEL_X"], p["LABEL_Y"])
places.update({
    "SG": (103.8, 1.35), "HK": (114.2, 22.3), "MO": (113.55, 22.2), "BH": (50.55, 26.0), "MT": (14.4, 35.9),
    "MU": (57.55, -20.3), "LI": (9.55, 47.15), "MC": (7.4, 43.75), "AD": (1.55, 42.5), "SC": (55.5, -4.7),
    "MV": (73.5, 3.2), "IM": (-4.5, 54.2), "GI": (-5.35, 36.15), "CW": (-69.0, 12.2), "PR": (-66.5, 18.2),
    "RE": (55.5, -21.1), "GU": (144.8, 13.45), "SM": (12.45, 43.95), "VA": (12.45, 41.9), "BM": (-64.75, 32.3),
    "KY": (-81.25, 19.3), "BB": (-59.55, 13.15), "JE": (-2.1, 49.2), "GG": (-2.55, 49.45), "FO": (-6.9, 62.0),
    "CV": (-23.6, 15.1), "ST": (6.6, 0.25), "KM": (43.35, -11.65), "WS": (-172.1, -13.75), "TO": (-175.2, -21.2),
})
# the US and Russia are labelled where their land is not: pull the marker to
# where their servers are
places["US"] = (-98.0, 39.0)
places["RU"] = (60.0, 57.0)
places["CA"] = (-100.0, 54.0)
# grid coordinates to a tenth of a cell, as "CCx,y"
table = ";".join(f"{k}{(lon + 180) / STEP:.1f},{(LAT_TOP - lat) / STEP:.1f}" for k, (lon, lat) in sorted(places.items()))

open("src/map-data.js", "w").write(
    "// Generated by tools/build_map.py from Natural Earth (public domain). Do not edit.\n"
    f"export const MAP = {{ cols: {COLS}, rows: {ROWS}, land: \"{hexmask}\",\n  places: \"{table}\" }}\n")
print(COLS, ROWS, sum(bits), "land cells,", len(places), "places")
for r in range(ROWS):
    print("".join("●" if bits[r * COLS + c] else " " for c in range(COLS)))
